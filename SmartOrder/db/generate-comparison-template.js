// Fonction pour convertir en CSV
function arrayToCSV(data) {
  return data
    .map((row) =>
      row
        .map((cell) => {
          // Échapper les guillemets et entourer de guillemets si nécessaire
          const cellStr = String(cell);
          if (
            cellStr.includes(",") ||
            cellStr.includes('"') ||
            cellStr.includes("\n")
          ) {
            return `"${cellStr.replace(/"/g, '""')}"`;
          }
          return cellStr;
        })
        .join(","),
    )
    .join("\n");
}

